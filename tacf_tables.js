/**
 * Função para obter o valor necessário para a pontuação máxima de um teste (10, 30 ou 50 pts)
 */
function obterValorMaximosPontos(sexo, oicKey, paramValue) {
    if (sexo === 'F' && !['cintura', 'flexao', 'abdominal', 'corrida', 'marcha'].includes(oicKey)) return null; // Apenas cintura, flexão, abdominal, corrida e marcha implementadas para F

    const config = TACF_TABLES[sexo][oicKey];
    const paramIndex = config.faixas.findIndex(f => paramValue <= f.max);
    if (paramIndex === -1) return null;
    
    let arrPts, propName;
    if (oicKey === 'cintura') { arrPts = sexo === 'M' ? PONTOS_CINTURA_M : PONTOS_CINTURA_F; propName = 'c'; }
    else if (oicKey === 'flexao') { arrPts = sexo === 'M' ? PONTOS_FLEXAO_M : PONTOS_FLEXAO_F; propName = 'r'; }
    else if (oicKey === 'abdominal') { arrPts = sexo === 'M' ? PONTOS_ABDOMINAL_M : PONTOS_ABDOMINAL_F; propName = 'r'; }
    else if (oicKey === 'corrida') { arrPts = sexo === 'M' ? PONTOS_CORRIDA_M : PONTOS_CORRIDA_F; propName = 'd'; }
    else if (oicKey === 'marcha') { arrPts = sexo === 'M' ? PONTOS_MARCHA_M : PONTOS_MARCHA_F; propName = 's'; }
    else return null;
    
    let maxPts = -1;
    for(let item of arrPts) {
        if (item.pts[paramIndex] > maxPts) maxPts = item.pts[paramIndex];
    }
    
    let targetValue = null;
    if (config.type === 'higher') {
        // procurar o menor valor que atinge maxPts
        for (let item of arrPts) {
            if (item.pts[paramIndex] === maxPts) {
                targetValue = item[propName];
                break;
            }
        }
    } else {
        // procurar o maior valor (mais fácil) que atinge maxPts
        for (let i = arrPts.length - 1; i >= 0; i--) {
            if (arrPts[i].pts[paramIndex] === maxPts) {
                targetValue = arrPts[i][propName];
                break;
            }
        }
    }
    
    return {
        limit: targetValue,
        type: config.type,
        maxPts: maxPts
    };
}

function calcularPontosCinturaMasculina(estatura, cintura) {
    const config = TACF_TABLES.M.cintura;
    const indexEstatura = config.faixas.findIndex(f => estatura <= f.max);
    
    if (indexEstatura === -1) return 0; // fallback

    let faixaPontos = PONTOS_CINTURA_M.find(item => item.c >= cintura);
    if (!faixaPontos) {
        faixaPontos = PONTOS_CINTURA_M[PONTOS_CINTURA_M.length - 1]; // >= 102.0
    }
    
    return faixaPontos.pts[indexEstatura];
}

