/**
 * Função utilitária para classificar um valor em I, S, B, MB, E
 */
function classificarDetalhado(valor, config, paramBase) {
    const faixa = config.faixas.find(f => paramBase <= f.max);
    if (!faixa) return { grau: 'I', proximo: null, falta: 0 };

    const t = faixa.t;
    if (config.type === 'higher') {
        if (valor >= t[3]) return { grau: 'E', proximo: null, falta: 0 };
        if (valor >= t[2]) return { grau: 'MB', proximo: 'E', falta: parseFloat((t[3] - valor).toFixed(2)) };
        if (valor >= t[1]) return { grau: 'B', proximo: 'MB', falta: parseFloat((t[2] - valor).toFixed(2)) };
        if (valor >= t[0]) return { grau: 'S', proximo: 'B', falta: parseFloat((t[1] - valor).toFixed(2)) };
        return { grau: 'I', proximo: 'S', falta: parseFloat((t[0] - valor).toFixed(2)) };
    } else { // lower is better
        if (valor <= t[3]) return { grau: 'E', proximo: null, falta: 0 };
        if (valor <= t[2]) return { grau: 'MB', proximo: 'E', falta: parseFloat((valor - t[3]).toFixed(2)) };
        if (valor <= t[1]) return { grau: 'B', proximo: 'MB', falta: parseFloat((valor - t[2]).toFixed(2)) };
        if (valor <= t[0]) return { grau: 'S', proximo: 'B', falta: parseFloat((valor - t[1]).toFixed(2)) };
        return { grau: 'I', proximo: 'S', falta: parseFloat((valor - t[0]).toFixed(2)) };
    }
}

function classificar(valor, config, paramBase) {
    return classificarDetalhado(valor, config, paramBase).grau;
}

