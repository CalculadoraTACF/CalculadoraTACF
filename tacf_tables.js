/**
 * Função que avalia o desempenho em todos os testes
 */
function avaliarDesempenho(sexo, idade, dados) {
    const table = TACF_TABLES[sexo];
    const results = {};

    // Cintura (baseada na estatura)
    const c_info = classificarDetalhado(dados.cintura, table.cintura, dados.estatura);
    
    let c_pontos = '--';
    if (sexo === 'M') {
        c_pontos = calcularPontosCinturaMasculina(dados.estatura, dados.cintura).toFixed(1);
    } else if (sexo === 'F') {
        c_pontos = calcularPontosCinturaFeminina(dados.estatura, dados.cintura).toFixed(1);
    }
    
    results.cintura = {
        valor: `${dados.cintura} cm`,
        grau: c_info.grau,
        apto: c_info.grau !== 'I',
        pontos: c_pontos,
        proximo: c_info.proximo,
        falta: c_info.falta
    };

    // Flexão (baseada na idade)
    const f_info = classificarDetalhado(dados.flexao, table.flexao, idade);
    
    let f_pontos = '--';
    if (sexo === 'M') {
        f_pontos = calcularPontosFlexaoMasculina(idade, dados.flexao).toFixed(1);
    } else if (sexo === 'F') {
        f_pontos = calcularPontosFlexaoFeminina(idade, dados.flexao).toFixed(1);
    }
    
    results.flexao = {
        valor: `${dados.flexao} reps`,
        grau: f_info.grau,
        apto: f_info.grau !== 'I',
        pontos: f_pontos,
        proximo: f_info.proximo,
        falta: f_info.falta
    };

    // Abdominal (baseada na idade)
    const a_info = classificarDetalhado(dados.abdominal, table.abdominal, idade);
    
    let a_pontos = '--';
    if (sexo === 'M') {
        a_pontos = calcularPontosAbdominalMasculina(idade, dados.abdominal).toFixed(1);
    } else if (sexo === 'F') {
        a_pontos = calcularPontosAbdominalFeminina(idade, dados.abdominal).toFixed(1);
    }
    
    results.abdominal = {
        valor: `${dados.abdominal} reps`,
        grau: a_info.grau,
        apto: a_info.grau !== 'I',
        pontos: a_pontos,
        proximo: a_info.proximo,
        falta: a_info.falta
    };

    // Aeróbico (Corrida ou Marcha)
    if (dados.isMarcha) {
        const tempoTotalSegundos = (parseInt(dados.marchaMin) * 60) + parseInt(dados.marchaSeg);
        const m_info = classificarDetalhado(tempoTotalSegundos, table.marcha, idade);

        let m_pontos = '--';
        if (sexo === 'M') {
            m_pontos = calcularPontosMarchaMasculina(idade, tempoTotalSegundos).toFixed(1);
        } else if (sexo === 'F') {
            m_pontos = calcularPontosMarchaFeminina(idade, tempoTotalSegundos).toFixed(1);
        }

        results.aerobico = {
            valor: `${dados.marchaMin}m ${dados.marchaSeg}s`,
            grau: m_info.grau,
            apto: m_info.grau !== 'I',
            pontos: m_pontos,
            proximo: m_info.proximo,
            falta: m_info.falta
        };
    } else {
        const r_info = classificarDetalhado(dados.corrida, table.corrida, idade);
        
        let r_pontos = '--';
        if (sexo === 'M') {
            r_pontos = calcularPontosCorridaMasculina(idade, dados.corrida).toFixed(1);
        } else if (sexo === 'F') {
            r_pontos = calcularPontosCorridaFeminina(idade, dados.corrida).toFixed(1);
        }
        
        results.aerobico = {
            valor: `${dados.corrida} m`,
            grau: r_info.grau,
            apto: r_info.grau !== 'I',
            pontos: r_pontos,
            proximo: r_info.proximo,
            falta: r_info.falta
        };
    }

    results.aptoGeral = results.cintura.apto && results.flexao.apto && results.abdominal.apto && results.aerobico.apto;
    return results;
}
